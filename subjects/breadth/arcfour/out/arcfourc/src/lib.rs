#![allow(dead_code, non_snake_case, clippy::needless_range_loop, unused_variables)]
#[allow(non_camel_case_types)] pub type BYTE = u8;





pub fn arcfour_key_setup(state: &mut [u8; 256], key: &[u8]) {
    let len = key.len();
    for i in 0..256 {
        state[i] = i as u8;
    }
    let mut j: usize = 0;
    for i in 0..256 {
        j = (j + state[i] as usize + key[i % len] as usize) % 256;
        state.swap(i, j);
    }
}
pub fn arcfour_generate_stream(state: &mut [u8; 256], out_len: usize) -> Vec<u8> {
    let mut i: usize = 0;
    let mut j: usize = 0;
    let mut out = vec![0u8; out_len];

    for idx in 0..out_len {
        i = (i + 1) % 256;
        j = (j + state[i] as usize) % 256;

        let t = state[i];
        state[i] = state[j];
        state[j] = t;

        let lookup_idx = (state[i] as usize + state[j] as usize) % 256;
        out[idx] = state[lookup_idx];
    }

    out
}

